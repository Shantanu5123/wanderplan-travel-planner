const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [selectedLanguage, setSelectedLanguage] = useState(() => {
    return localStorage.getItem('wanderplan_lang') || 'en';
  });

  const languageObj = SUPPORTED_LANGUAGES.find((l) => l.code === selectedLanguage) || SUPPORTED_LANGUAGES[0];

  const changeLanguage = (code) => {
    setSelectedLanguage(code);
    localStorage.setItem('wanderplan_lang', code);
  };

  const t = (key) => {
    const langDict = TRANSLATIONS[selectedLanguage] || TRANSLATIONS['en'];
    return langDict[key] || TRANSLATIONS['en'][key] || key;
  };

  return (
    <LanguageContext.Provider value={{ selectedLanguage, languageObj, languages: SUPPORTED_LANGUAGES, changeLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
